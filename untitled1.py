import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

rng = np.random.default_rng(42)
os.makedirs("outputs", exist_ok=True)

# assumptions (also written to the excel file at the end)
N_SKU, N_SUP, DAYS = 120, 8, 365
EXCESS_DAYS = 60          # more than this many days of cover = excess
Z_95 = 1.65
Z_ABC = {"A": 2.05, "B": 1.65, "C": 1.28}      # 98 / 95 / 90 % cycle service
Z_LEAN = {"A": 1.65, "B": 1.28, "C": 0.84}     # 95 / 90 / 80 %
BUDGET_MULT = 4           # safety stock budget = 4x what the current policy holds
N_SIM = 4000

# %% 0. build the dataset (synthetic, since no public set has all 5 tables)
sup = pd.DataFrame({
    "supplier_id": [f"S{i:02d}" for i in range(1, N_SUP + 1)],
    "quoted_lt": rng.integers(6, 25, N_SUP),
    "lt_bias": rng.uniform(0, 5, N_SUP).round(1),     # real lead time is slower than quoted by this
    "lt_sd": rng.uniform(1.0, 6.5, N_SUP).round(1),
    "short_ship": rng.choice([0, 0, 0.05, 0.12], N_SUP),
})
sup_i = sup.set_index("supplier_id")

prod = pd.DataFrame({
    "sku": [f"P{i:03d}" for i in range(N_SKU)],
    "supplier_id": rng.choice(sup.supplier_id, N_SKU),
    "unit_cost": rng.lognormal(3, 0.9, N_SKU).round(2),
    "avg_demand": rng.lognormal(2.3, 0.8, N_SKU).clip(1).round(1),
    "demand_cv": rng.uniform(0.15, 1.4, N_SKU).round(2),
    "order_days": rng.integers(25, 100, N_SKU),
})
prod["rop_current"] = prod.avg_demand * (prod.supplier_id.map(sup_i.quoted_lt) + 3)

dates = pd.date_range("2025-01-01", periods=DAYS)
daily_rows, po_rows = [], []
po_n = 0

for p in prod.itertuples():
    s = sup_i.loc[p.supplier_id]
    on_hand = int(p.avg_demand * 25)
    arrivals = {}
    qty = max(1, int(p.avg_demand * p.order_days))
    for t in range(DAYS):
        opening = on_hand
        rec = arrivals.pop(t, 0)
        on_hand += rec
        demand = max(0, int(rng.normal(p.avg_demand, p.avg_demand * p.demand_cv)))
        sold = min(on_hand, demand)
        on_hand -= sold
        daily_rows.append((dates[t], p.sku, opening, rec, demand, sold, on_hand))

        if on_hand + sum(arrivals.values()) <= p.rop_current:
            lt = max(1, int(round(rng.normal(s.quoted_lt + s.lt_bias, s.lt_sd))))
            got = qty if s.short_ship == 0 else max(1, int(qty * (1 - rng.uniform(0, 2 * s.short_ship))))
            po_n += 1
            arr = t + lt
            if arr < DAYS:
                arrivals[arr] = arrivals.get(arr, 0) + got
            po_rows.append((
                f"PO{po_n:05d}", p.sku, p.supplier_id, dates[t],
                dates[t] + pd.Timedelta(days=int(s.quoted_lt)),
                dates[arr] if arr < DAYS else pd.NaT,
                qty, got if arr < DAYS else np.nan))

daily = pd.DataFrame(daily_rows, columns=["date", "sku", "opening", "receipts", "demand", "sold", "closing"])
po = pd.DataFrame(po_rows, columns=["po_id", "sku", "supplier_id", "order_date",
                                    "promised_date", "received_date", "qty_ordered", "qty_received"])

# put some mess in on purpose so the validation step has something to find
po = pd.concat([po, po.sample(12, random_state=1)], ignore_index=True)           # duplicate rows
orph = po.sample(6, random_state=2).copy()
orph["sku"] = [f"P9{i:02d}" for i in range(6)]
orph["po_id"] = [f"PX{i}" for i in range(6)]
po = pd.concat([po, orph], ignore_index=True)                                    # unknown skus
po.loc[po.sample(5, random_state=3).index, "supplier_id"] = "S99"                # unknown supplier
po.loc[po.sample(4, random_state=4).index, "qty_ordered"] *= -1                  # negative qty
bad = daily.sample(30, random_state=5).index
daily.loc[bad, "closing"] += rng.choice([-1, 1], 30) * rng.integers(3, 20, 30)   # wrong balances

print("rows:", len(prod), "products,", len(sup), "suppliers,", len(po), "POs,", len(daily), "daily records")

# %% 1. validate keys and reconcile inventory
log = []
def note(issue, n, treatment):
    log.append({"issue": issue, "rows": int(n), "treatment": treatment})

note("duplicate po_id", po.duplicated("po_id").sum(), "dropped, kept first")
note("PO sku not in product master", (~po.sku.isin(prod.sku)).sum(), "dropped (cannot be mapped)")
note("PO supplier not in supplier master", (~po.supplier_id.isin(sup.supplier_id)).sum(),
     "supplier taken from product master")
note("PO qty_ordered <= 0", (po.qty_ordered <= 0).sum(), "dropped")
note("PO still open at year end (no receipt)", po.received_date.isna().sum(),
     "kept, excluded from lead time stats")
note("daily sku not in product master", (~daily.sku.isin(prod.sku)).sum(), "none found")

daily = daily.sort_values(["sku", "date"]).reset_index(drop=True)
daily["expected_close"] = daily.opening + daily.receipts - daily.sold
daily["diff"] = daily.closing - daily.expected_close
daily["gap"] = daily.opening - daily.groupby("sku").closing.shift()
note("closing != opening + receipts - sold", (daily["diff"] != 0).sum(),
     "closing recomputed from movements")
note("opening != previous day closing", (daily["gap"].fillna(0) != 0).sum(),
     "fixed by the closing correction")

# cleaning
po_c = po.drop_duplicates("po_id")
po_c = po_c[po_c.sku.isin(prod.sku)]
bad_sup = ~po_c.supplier_id.isin(sup.supplier_id)
po_c.loc[bad_sup, "supplier_id"] = po_c.loc[bad_sup, "sku"].map(prod.set_index("sku").supplier_id)
po_c = po_c[po_c.qty_ordered > 0].copy()

daily["closing"] = daily.expected_close
daily["gap"] = daily.opening - daily.groupby("sku").closing.shift()
assert (daily.gap.fillna(0) == 0).all(), "roll-forward still broken"
daily = daily.drop(columns=["expected_close", "diff", "gap"])

dq_log = pd.DataFrame(log)
print("\n--- data quality log ---")
print(dq_log.to_string(index=False))
print("clean POs:", len(po_c), " (raw", len(po), ")")

# %% 2. lead times and supplier reliability
done = po_c.dropna(subset=["received_date"]).copy()
done["lead_time"] = (done.received_date - done.order_date).dt.days
done["late_days"] = (done.received_date - done.promised_date).dt.days.clip(lower=0)
done["on_time"] = done.late_days == 0

sup_score = done.groupby("supplier_id").agg(
    n_po=("po_id", "count"),
    lt_mean=("lead_time", "mean"),
    lt_std=("lead_time", "std"),
    lt_p90=("lead_time", lambda x: x.quantile(0.9)),
    otd_pct=("on_time", "mean"),
    avg_late=("late_days", "mean"),
    qty_ord=("qty_ordered", "sum"),
    qty_rec=("qty_received", "sum"),
)
sup_score["fill_rate"] = sup_score.qty_rec / sup_score.qty_ord
sup_score["quoted_lt"] = sup_i.quoted_lt
sup_score["lt_gap"] = sup_score.lt_mean - sup_score.quoted_lt

# %% 3. demand variability, safety stock proxy, days of cover
g = daily.groupby("sku")
item = prod.set_index("sku")[["supplier_id", "unit_cost", "rop_current"]].copy()
item["d_mean"] = g.demand.mean()
item["d_std"] = g.demand.std()
item["d_cv"] = item.d_std / item.d_mean
item = item.join(sup_score[["lt_mean", "lt_std"]], on="supplier_id")

item["ss_95"] = Z_95 * np.sqrt(item.lt_mean * item.d_std ** 2 + item.d_mean ** 2 * item.lt_std ** 2)
item["rop_95"] = item.d_mean * item.lt_mean + item.ss_95
item["on_hand"] = daily[daily.date == daily.date.max()].set_index("sku").closing
item["avg_on_hand"] = g.closing.mean()
item["days_cover"] = item.on_hand / item.d_mean
item["order_qty"] = po_c.groupby("sku").qty_ordered.mean()
item["order_qty"] = item.order_qty.fillna(item.d_mean * 30)

# stockouts, observed
short = daily.demand - daily.sold
item["stockout_days"] = (short > 0).groupby(daily.sku).sum()
item["stockout_rate"] = item.stockout_days / DAYS
item["lost_units"] = short.groupby(daily.sku).sum()
item["fill_rate_obs"] = g.sold.sum() / g.demand.sum()
item["lost_value"] = item.lost_units * item.unit_cost

# excess
item["excess_units"] = (item.on_hand - item.d_mean * EXCESS_DAYS).clip(lower=0)
item["excess_value"] = item.excess_units * item.unit_cost

# late delivery exposure = days late x daily demand value of the item
done = done.join(item[["d_mean", "unit_cost"]], on="sku")
done["late_exposure"] = done.late_days * done.d_mean * done.unit_cost
sup_score["late_exposure"] = done.groupby("supplier_id").late_exposure.sum()
item["late_exposure"] = done.groupby("sku").late_exposure.sum()
item["late_exposure"] = item.late_exposure.fillna(0)

# %% 4. ABC / XYZ
item["annual_value"] = item.d_mean * 365 * item.unit_cost
item = item.sort_values("annual_value", ascending=False)
item["cum_pct"] = item.annual_value.cumsum() / item.annual_value.sum()
item["ABC"] = pd.cut(item.cum_pct, [0, 0.8, 0.95, 1.0001], labels=list("ABC")).astype(str)
item["XYZ"] = pd.cut(item.d_cv, [0, 0.5, 1.0, np.inf], labels=list("XYZ")).astype(str)
item["segment"] = item.ABC + item.XYZ
seg_table = pd.crosstab(item.ABC, item.XYZ)
print("\n--- ABC/XYZ counts ---")
print(seg_table)

# %% 5. monte carlo: uncertain lead time (lognormal) and demand during lead time
def simulate(d_mean, d_std, lt_mean, lt_std, stock, n=N_SIM, seed=7):
    # same seed every call so scenarios are compared on the same random draws
    r = np.random.default_rng(seed)
    m = lt_mean[:, None]
    s = np.maximum(lt_std, 0.01)[:, None]
    v = np.log(1 + (s / m) ** 2)
    lt = np.maximum(np.exp(r.normal(np.log(m) - v / 2, np.sqrt(v), (len(d_mean), n))), 1)
    dem = np.maximum(r.normal(d_mean[:, None] * lt, d_std[:, None] * np.sqrt(lt)), 0)
    gap = np.maximum(dem - stock[:, None], 0)
    return (gap > 0).mean(axis=1), gap.mean(axis=1)    # P(stockout in a cycle), expected units short

def run(name, z=None, worst=(), std_cut=0.0, mean_cut=0.0):
    df = item.copy()
    hit = df.supplier_id.isin(worst)
    df.loc[hit, "lt_std"] *= 1 - std_cut
    df.loc[hit, "lt_mean"] *= 1 - mean_cut
    dm, ds = df.d_mean.to_numpy(), df.d_std.to_numpy()
    lm, ls = df.lt_mean.to_numpy(), df.lt_std.to_numpy()
    stock = df.rop_current.to_numpy()
    if z is not None:
        zz = z.reindex(df.index).to_numpy()
        new = dm * lm + zz * np.sqrt(lm * ds ** 2 + dm ** 2 * ls ** 2)
        stock = np.where(np.isnan(zz), stock, new)
    p_so, exp_short = simulate(dm, ds, lm, ls, stock)
    cycles = dm * 365 / df.order_qty.to_numpy()
    yearly_short = exp_short * cycles
    fill = 1 - np.clip(yearly_short / (dm * 365), 0, 1)
    w = dm * 365
    return {
        "scenario": name,
        "cycle_service": 1 - p_so.mean(),
        "fill_rate": (fill * w).sum() / w.sum(),
        "ss_investment": (np.maximum(stock - dm * lm, 0) * df.unit_cost.to_numpy()).sum(),
        "exp_lost_value": (yearly_short * df.unit_cost.to_numpy()).sum(),
    }, p_so

base_res, item["p_stockout"] = run("Baseline (current ROP)")
obs_fill = 1 - item.lost_units.sum() / (item.d_mean * DAYS).sum()
print("\nsimulated baseline fill rate: %.3f | observed in data: %.3f" % (base_res["fill_rate"], obs_fill))

# how risk drops as stock rises (for the report chart)
mult = np.arange(0.5, 2.01, 0.25)
curve = []
for k in mult:
    p_so, _ = simulate(item.d_mean.to_numpy(), item.d_std.to_numpy(), item.lt_mean.to_numpy(),
                       item.lt_std.to_numpy(), item.rop_current.to_numpy() * k)
    curve.append(1 - p_so.mean())

# %% 6. risk ranking + sensitivity
risk_cols = ["p_stockout", "lost_value", "sup_risk", "d_cv"]
item["sup_risk"] = item.supplier_id.map(1 - sup_score.otd_pct)
weights = np.array([0.35, 0.30, 0.20, 0.15])

def norm(s):
    return (s - s.min()) / (s.max() - s.min())

R = np.column_stack([norm(item[c]).to_numpy() for c in risk_cols])
item["risk_score"] = R @ weights
top_idx = set(np.argsort(-item.risk_score.to_numpy())[:20])

hits = np.zeros(len(item))
overlaps = []
for _ in range(500):
    w = rng.dirichlet(weights * 40)
    t = np.argsort(-(R @ w))[:20]
    hits[t] += 1
    overlaps.append(len(top_idx & set(t)) / 20)
item["top20_freq"] = hits / 500
print("\nsensitivity: average top-20 overlap with base weights = %.2f" % np.mean(overlaps))

item["action"] = np.where(item.days_cover < item.lt_mean, "order / expedite now",
                  np.where(item.days_cover > EXCESS_DAYS, "hold orders, excess", "monitor"))
top20 = item.sort_values("risk_score", ascending=False).head(20)
cols = ["supplier_id", "segment", "p_stockout", "stockout_rate", "lost_value", "days_cover",
        "risk_score", "top20_freq", "action"]
print("\n--- top 20 items ---")
print(top20[cols].round(3).to_string())

# %% 7. scenarios
worst3 = sup_score.otd_pct.nsmallest(3).index.tolist()
z_flat = pd.Series(Z_95, index=item.index)
z_abc = item.ABC.map(Z_ABC)
z_lean = item.ABC.map(Z_LEAN)

z_target = pd.Series(np.nan, index=item.index)
z_target[top20.index] = Z_95

res = [base_res]
res.append(run("S1: 95% for every item", z=z_flat)[0])
res.append(run("S2: ABC differentiated (98/95/90)", z=z_abc)[0])
res.append(run("S3: lean ABC (95/90/80)", z=z_lean)[0])
res.append(run("S4: only top-20 risk items to 95%", z=z_target)[0])
res.append(run("S5: lean ABC + fix 3 worst suppliers", z=z_lean, worst=worst3, std_cut=0.3, mean_cut=0.1)[0])

scen = pd.DataFrame(res)
budget = scen.ss_investment.iloc[0] * BUDGET_MULT
scen["within_budget"] = scen.ss_investment <= budget
scen["fill_gain_pts"] = (scen.fill_rate - scen.fill_rate.iloc[0]) * 100
scen["extra_invest"] = scen.ss_investment - scen.ss_investment.iloc[0]
scen["extra_cost_per_pt"] = (scen.extra_invest / scen.fill_gain_pts).where(scen.fill_gain_pts > 0)
print("\n--- scenarios (budget = %.0f) ---" % budget)
print(scen.round(3).to_string(index=False))
print("worst suppliers used in S5:", worst3)

